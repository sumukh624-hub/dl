import numpy as np


# ============================================================
# XOR INPUT AND OUTPUT
# ============================================================

X = np.array([
    [0, 0],
    [0, 1],
    [1, 0],
    [1, 1]
])

y = np.array([
    [0],
    [1],
    [1],
    [0]
])


# ============================================================
# INITIALIZE WEIGHTS AND BIASES
# ============================================================

np.random.seed(1)

W1 = np.random.randn(2, 4)

W2 = np.random.randn(4, 1)

b1 = np.zeros((1, 4))

b2 = np.zeros((1, 1))


# ============================================================
# SIGMOID
# ============================================================

def sigmoid(x):

    return 1 / (
        1 + np.exp(-x)
    )


# ============================================================
# TRAINING
# ============================================================

for _ in range(10000):

    # Forward propagation

    h = sigmoid(
        X @ W1 + b1
    )

    o = sigmoid(
        h @ W2 + b2
    )


    # Error

    e = y - o


    # Backpropagation

    d2 = (
        e
        * o
        * (1 - o)
    )

    d1 = (
        d2 @ W2.T
    ) * h * (1 - h)


    # Update weights

    W2 += (
        h.T @ d2
    ) * 0.1

    W1 += (
        X.T @ d1
    ) * 0.1


    # Update biases

    b2 += (
        d2.sum(axis=0)
    ) * 0.1

    b1 += (
        d1.sum(axis=0)
    ) * 0.1


# ============================================================
# OUTPUT
# ============================================================

print(
    (o >= 0.5).astype(int)
)